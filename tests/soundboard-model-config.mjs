import assert from 'node:assert/strict';
import {constructSoundboardModelConfig} from '../dsp/soundboard-model-config.mjs';
const model=new Uint8Array(0x1e8),preset=new Uint8Array(0x1840),m=new DataView(model.buffer),p=new DataView(preset.buffer);
m.setFloat32(0x50,-2,true);m.setFloat32(0x54,1.4,true);m.setFloat32(0x58,0.85,true);m.setFloat32(0x128,0.4,true);
m.setUint32(0x9c,1,true);p.setFloat32(0xf98,3,true);p.setFloat32(0x1020,0.25,true);
const input={model,preset,bridge:Float32Array.of(0.4,0.85,0.9,0.15),propagationModes:Float32Array.of(2,2,2),component:1,rootLidEnabled:false};
const value=(r,o)=>new DataView(r.config.buffer).getFloat32(o,true);
const ordinary=constructSoundboardModelConfig(input);
assert.equal(value(ordinary,0x38),6);
assert.equal(value(ordinary,0x40),1);
assert.equal(ordinary.config[0x1d0],1);
assert.equal(ordinary.outputRateComputed,false);
const rateConfigured=constructSoundboardModelConfig({...input,runtimeRates:{baseRate:44100,renderRate:96000}});
assert.equal(value(rateConfigured,0x2c),48000);
assert.equal(rateConfigured.outputRateComputed,true);
assert.equal(rateConfigured.ratePolicy.selectedRatio,2);
assert.equal(rateConfigured.computedOffsets.length,31);
assert.equal(value(constructSoundboardModelConfig({...input,rootLidEnabled:true}),0x40),0.25);
assert.equal(value(constructSoundboardModelConfig({...input,twoPosition:true}),0x80),0.5);
assert.equal(value(constructSoundboardModelConfig({...input,component:2,twoPosition:true}),0x80),Math.fround(0.6));
assert.equal(value(constructSoundboardModelConfig({...input,component:44,linearPosition:true}),0x80),0.5);
assert.throws(()=>constructSoundboardModelConfig({...input,rootLidEnabled:null}),/root lid/);
m.setUint32(0x98,1,true);
assert.throws(()=>constructSoundboardModelConfig(input),/geometry family/);
console.log('PASS model height scaling, lid enable policy, source-position branches and unsupported-family guards');
