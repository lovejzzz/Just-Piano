import assert from 'node:assert/strict';
import {soundboardCurveGain} from '../dsp/soundboard-curve-gain.mjs';
const controls = {length: 5, smoothingWidth: 40, mix: 0.25, binSpacing: 10};
const curve = {x: Float32Array.of(10, 30), y: Float32Array.of(-2, 2), dimensions: 1, mode: 0, logX: 0};
const original = curve.y.slice();
const result = soundboardCurveGain(curve, controls);
assert.deepEqual(result.interpolated, Float32Array.of(-4, -2, 0, 2, 4));
assert.equal(result.beforeSmoothing[2], 1);
assert.deepEqual(curve.y, original);
const two = soundboardCurveGain({...curve, dimensions: 2, y: Float32Array.of(0, 4, 4, 8)}, controls);
assert.deepEqual(two.interpolated, Float32Array.of(-2, 2, 0, 4, 2, 6, 4, 8, 6, 10));
assert.ok(two.beforeSmoothing[0] < 1 && two.beforeSmoothing[1] > 1);
const flat = soundboardCurveGain({...curve, x: new Float32Array(), y: Float32Array.of(0)}, controls);
assert.ok(flat.interpolated.every((v) => v === 0));
assert.ok(flat.beforeSmoothing.every((v) => v === 1));
assert.throws(() => soundboardCurveGain({...curve, mode: 1}, controls), /Supported/);
assert.throws(() => soundboardCurveGain({...curve, logX: 1}, controls), /Supported/);
assert.throws(() => soundboardCurveGain({...curve, x: Float32Array.of(10, 10)}, controls), /Supported/);
assert.throws(() => soundboardCurveGain(curve, {...controls, smoothingWidth: 0}), /Supported/);
console.log('PASS curve extrapolation, two-output blend, exact zero dB, constant curve and mode guards');
