import assert from 'node:assert/strict';
import {createSoundboardResamplingPlan, soundboardResamplingRatio, resampleSoundboardResponse} from '../dsp/soundboard-resampling.mjs';
assert.deepEqual(soundboardResamplingRatio(Math.fround(48000 / 44100)), {numerator: 160, denominator: 147});
assert.deepEqual(soundboardResamplingRatio(0.5), {numerator: 1, denominator: 2});
assert.deepEqual(soundboardResamplingRatio(1.5), {numerator: 3, denominator: 2});
const input = Float32Array.of(1, -0, 2, -3), identity = createSoundboardResamplingPlan(1);
const result = resampleSoundboardResponse(input, identity);
assert.deepEqual(result.output, input); assert.notEqual(result.output, input);
const plan = createSoundboardResamplingPlan(2), impulse = new Float32Array(16); impulse[0] = 1;
const out = resampleSoundboardResponse(impulse, plan);
assert.equal(out.frames, 32); assert.equal(out.output.length, 64);
assert.equal(out.output[0], 1);
assert.ok(out.output.slice(32).every((v) => v === 0));
assert.deepEqual(impulse, Float32Array.from({length: 16}, (_, i) => i === 0 ? 1 : 0));
assert.equal(resampleSoundboardResponse(new Float32Array(), plan).output.length, 0);
assert.ok(resampleSoundboardResponse(new Float32Array(4), plan).output.every((v) => v === 0));
assert.throws(() => createSoundboardResamplingPlan(0), /ratio/);
assert.throws(() => createSoundboardResamplingPlan(2, 0), /quality/);
assert.throws(() => resampleSoundboardResponse(Float32Array.of(NaN), plan), /Finite/);
assert.throws(() => resampleSoundboardResponse(input, {...plan, coefficients: Float32Array.of(1)}), /plan/);
console.log('PASS rational ratios, identity ownership, impulse alignment, padding, zero response and resampling guards');
